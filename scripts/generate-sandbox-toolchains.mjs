#!/usr/bin/env node
/**
 * Generates src/lib/storefront/theme-framework/theme-toolchains.generated.ts
 * from the Sandbox image's own toolchain manifests.
 *
 * Order, so nothing depends on itself: the image installs each toolchain from
 * its lockfile and writes its manifest (Dockerfile.sandbox,
 * sandbox/toolchain-manifest.mjs); this script builds that image under an
 * explicit tag, reads the manifests out of it, checks each identity against the
 * manifest's bytes, and writes the registry. The image never reads the
 * registry. Then Morph is built.
 *
 *   node scripts/generate-sandbox-toolchains.mjs [--image <tag>]
 *
 * Without --image it builds `morph-sandbox-toolchains:registry` first. Docker
 * is required; nothing is pushed or deployed.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const outputPath = path.join(
  root,
  "src/lib/storefront/theme-framework/theme-toolchains.generated.ts",
);
const TOOLCHAINS = [
  {
    root: "/opt/morph-toolchain/tanstack-start-1.168",
    framework: "tanstack-start",
  },
  { root: "/opt/morph-toolchain/astro-7.3", framework: "astro" },
];
const PLATFORM = { root: "/opt/morph-platform", framework: "platform" };

const args = process.argv.slice(2);
const imageFlag = args.indexOf("--image");
let image = imageFlag >= 0 ? args[imageFlag + 1] : undefined;
if (!image) {
  image = "morph-sandbox-toolchains:registry";
  console.log(`building ${image} from Dockerfile.sandbox…`);
  execFileSync(
    "docker",
    ["build", "-f", "Dockerfile.sandbox", "-t", image, "."],
    { cwd: root, stdio: "inherit" },
  );
}

function readFromImage(file) {
  return execFileSync(
    "docker",
    ["run", "--rm", "--network", "none", "--entrypoint", "cat", image, file],
    { encoding: "buffer" },
  );
}

function entryFor({ root: toolchainRoot, framework }) {
  const manifestBytes = readFromImage(
    `${toolchainRoot}/toolchain.manifest.json`,
  );
  const recordedId = readFromImage(`${toolchainRoot}/toolchain.id`)
    .toString("utf8")
    .trim();
  const id = createHash("sha256").update(manifestBytes).digest("hex");
  if (id !== recordedId) {
    throw new Error(
      `${toolchainRoot}: toolchain.id ${recordedId} is not the SHA-256 of its manifest (${id}).`,
    );
  }
  const manifest = JSON.parse(manifestBytes.toString("utf8"));
  if (manifest.framework !== framework) {
    throw new Error(
      `${toolchainRoot}: manifest says framework "${manifest.framework}", expected "${framework}".`,
    );
  }
  return {
    id,
    framework,
    root: toolchainRoot,
    manifestFormat: manifest.manifestFormat,
    packageJsonSha256: manifest.packageJsonSha256,
    packageLockSha256: manifest.packageLockSha256,
    installedPositions: manifest.installed.length,
    directDependencies: manifest.packageJson.dependencies,
    node: manifest.node,
    npm: manifest.npm,
    baseImage: manifest.baseImage,
    platform: manifest.platform,
  };
}

// The lockfiles in the repository must be the ones the image installed.
function assertRepositoryLockfiles(entry, repositoryDirectory) {
  const sha = (file) =>
    createHash("sha256")
      .update(readFileSync(path.join(root, repositoryDirectory, file)))
      .digest("hex");
  if (sha("package.json") !== entry.packageJsonSha256) {
    throw new Error(
      `${repositoryDirectory}/package.json differs from the one in ${image}.`,
    );
  }
  if (sha("package-lock.json") !== entry.packageLockSha256) {
    throw new Error(
      `${repositoryDirectory}/package-lock.json differs from the one in ${image}.`,
    );
  }
}

const toolchains = TOOLCHAINS.map(entryFor);
const platform = entryFor(PLATFORM);
assertRepositoryLockfiles(
  toolchains[0],
  "sandbox/toolchains/tanstack-start-1.168",
);
assertRepositoryLockfiles(toolchains[1], "sandbox/toolchains/astro-7.3");
assertRepositoryLockfiles(platform, "sandbox/platform");

const source = `/* eslint-disable */
// Generated by scripts/generate-sandbox-toolchains.mjs from the Sandbox image's
// toolchain manifests. Do not edit by hand.
// prettier-ignore
export const GENERATED_SANDBOX_TOOLCHAINS = ${JSON.stringify(toolchains, null, 2)} as const;
// prettier-ignore
export const GENERATED_SANDBOX_PLATFORM_TOOLS = ${JSON.stringify(platform, null, 2)} as const;
`;
let previous = "";
try {
  previous = readFileSync(outputPath, "utf8");
} catch {}
if (previous !== source) writeFileSync(outputPath, source);
console.log(
  `${previous === source ? "unchanged" : "wrote"} ${path.relative(root, outputPath)}: ${toolchains
    .map((t) => `${t.framework} ${t.id.slice(0, 12)}`)
    .join(", ")}, platform ${platform.id.slice(0, 12)}`,
);
