import type { StorefrontPreviewAccessKind } from "@/db/storefront.schema";
import type {
  PreviewAccessAuthorityRecord,
  PreviewAccessGrantRecord,
  StorefrontPreviewAccessDAL,
} from "../../dal/storefront-preview-access.dal";
import { mayPreview } from "../build-preview/build-preview-capability";

/**
 * Private Live Preview access: the exchange that turns the editor's signed-in
 * session into a credential for one preview host in one browser, and the
 * check every preview request is answered by
 * (handoff/2026-10-28/preview-access-design.md §3–§5, §8).
 *
 * - A **code** is issued to the signed-in editor for a binder hash that came
 *   from the preview frame (or tab) it opened. Redeeming it needs the binder
 *   itself, which only that browser holds, so a code obtained anywhere else
 *   cannot be redeemed, and failing to redeem it consumes nothing.
 * - A **grant** is the credential the redeeming browser then holds. It is
 *   checked again on every request against its session, user and Theme, so
 *   signing out, a ban, a role change or a removed Theme refuses the next
 *   request.
 *
 * Only SHA-256 hashes of codes, binders and tokens are stored. Authorising the
 * editor's request to issue (session, role, Theme ownership, and that the
 * preview is this user's) is the caller's: the server function that issues
 * runs behind the same middleware and helpers as `startThemePreviewServer`.
 */

export const PREVIEW_ACCESS_EXCHANGE_TTL_MS = 60_000;
export const PREVIEW_ACCESS_GRANT_MAX_MS = 12 * 60 * 60_000;
/**
 * How long a grant may wait for its first verified request. A grant whose
 * cookie never reached the browser is never used, and is refused from then on.
 */
export const PREVIEW_ACCESS_ACTIVATION_WINDOW_MS = 120_000;
const SECRET_BYTES = 32;
const SECRET_PATTERN = /^[0-9a-f]{64}$/;
/** A flow id: 16 random bytes in hex, generated by the editor per attempt. */
const FLOW_ID_PATTERN = /^[0-9a-f]{32}$/;

export type PreviewAccessRefusal =
  | "BINDER_INVALID"
  | "FLOW_INVALID"
  | "FLOW_IN_USE"
  | "EXCHANGE_INVALID"
  | "USER_NOT_AUTHORIZED"
  | "THEME_NOT_LIVE"
  | "SESSION_ENDED"
  | "GRANT_NOT_CREATED"
  | "GRANT_UNKNOWN"
  | "GRANT_REVOKED"
  | "GRANT_EXPIRED"
  | "GRANT_NOT_ACTIVATED"
  | "HOST_MISMATCH";

export type VerifiedPreviewAccessGrant = Readonly<{
  id: string;
  flowId: string;
  kind: StorefrontPreviewAccessKind;
  sessionId: string;
  userId: string;
  storefrontId: string;
  themeId: string;
  previewId: string;
  previewHost: string;
  expiresAt: string;
}>;

function toHex(bytes: Uint8Array): string {
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join(
    "",
  );
}

/** A fresh random secret: a code, a binder or a grant token. */
export function createPreviewAccessSecret(): string {
  return toHex(crypto.getRandomValues(new Uint8Array(SECRET_BYTES)));
}

export async function hashPreviewAccessSecret(secret: string): Promise<string> {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(secret),
  );
  return toHex(new Uint8Array(digest));
}

/** Why the authority a code or grant answers to no longer holds, or null. */
function authorityRefusal(
  authority: PreviewAccessAuthorityRecord,
  userId: string,
  nowMs: number,
): PreviewAccessRefusal | null {
  if (
    !authority.session ||
    authority.session.userId !== userId ||
    !(nowMs < authority.session.expiresAtMs)
  ) {
    return "SESSION_ENDED";
  }
  if (!mayPreview(authority.user)) return "USER_NOT_AUTHORIZED";
  if (!authority.themeLive) return "THEME_NOT_LIVE";
  return null;
}

/**
 * Issues a code for an exchange the caller has already authorised, bound to
 * the binder hash the preview frame or tab reported and to the flow that
 * frame or tab was opened for. A flow gets one code: a second issue for the
 * same flow is refused and the first code stays valid.
 */
export async function issuePreviewAccessExchange(input: {
  dal: StorefrontPreviewAccessDAL;
  kind: StorefrontPreviewAccessKind;
  sessionId: string;
  userId: string;
  storefrontId: string;
  themeId: string;
  previewId: string;
  previewHost: string;
  flowId: string;
  binderHash: string;
  now?: Date;
}): Promise<
  | Readonly<{ ok: true; code: string; expiresAt: string }>
  | Readonly<{ ok: false; reason: PreviewAccessRefusal }>
> {
  if (!FLOW_ID_PATTERN.test(input.flowId)) {
    return { ok: false, reason: "FLOW_INVALID" };
  }
  if (!SECRET_PATTERN.test(input.binderHash)) {
    return { ok: false, reason: "BINDER_INVALID" };
  }
  const now = input.now ?? new Date();
  const code = createPreviewAccessSecret();
  const expiresAt = new Date(
    now.getTime() + PREVIEW_ACCESS_EXCHANGE_TTL_MS,
  ).toISOString();
  const stored = await input.dal.issueExchange({
    id: crypto.randomUUID(),
    flowId: input.flowId,
    codeHash: await hashPreviewAccessSecret(code),
    binderHash: input.binderHash,
    kind: input.kind,
    sessionId: input.sessionId,
    userId: input.userId,
    storefrontId: input.storefrontId,
    themeId: input.themeId,
    previewId: input.previewId,
    previewHost: input.previewHost,
    expiresAt,
    now: now.toISOString(),
  });
  if (!stored) return { ok: false, reason: "FLOW_IN_USE" };
  return { ok: true, code, expiresAt };
}

/**
 * Redeems a code on the preview host it was issued for, in the browser that
 * presents its binder, and creates the grant that browser will hold.
 *
 * The code is consumed before the grant is created. If the authority no
 * longer holds, or creating the grant fails, the code stays consumed and the
 * editor starts a new exchange, which needs its live session again; nothing
 * is retried here.
 */
export async function redeemPreviewAccessExchange(input: {
  dal: StorefrontPreviewAccessDAL;
  flowId: string;
  code: string;
  binder: string;
  previewHost: string;
  kind: StorefrontPreviewAccessKind;
  now?: Date;
  /**
   * Grants the redeeming browser already holds on this host (addendum A4.1,
   * user decision 2026-11-01: reuse first). After the code is consumed, one
   * of them is reused, and no grant or cookie is created, if it belongs to
   * the very session, user, storefront, Theme, preview, host and kind the
   * code was issued for, is activated, holds every check now, and has at
   * least `minRemainingMs` left. The partition is never itself a reason.
   */
  reuse?: Readonly<{ tokens: readonly string[]; minRemainingMs: number }>;
}): Promise<
  | Readonly<{
      ok: true;
      /** The new grant's token; absent when an existing grant was reused. */
      token?: string;
      grant: VerifiedPreviewAccessGrant;
    }>
  | Readonly<{ ok: false; reason: PreviewAccessRefusal }>
> {
  if (
    !FLOW_ID_PATTERN.test(input.flowId) ||
    !SECRET_PATTERN.test(input.code) ||
    !SECRET_PATTERN.test(input.binder)
  ) {
    return { ok: false, reason: "EXCHANGE_INVALID" };
  }
  const now = input.now ?? new Date();
  const exchange = await input.dal.consumeExchange({
    flowId: input.flowId,
    codeHash: await hashPreviewAccessSecret(input.code),
    binderHash: await hashPreviewAccessSecret(input.binder),
    previewHost: input.previewHost,
    kind: input.kind,
    now: now.toISOString(),
  });
  if (!exchange) return { ok: false, reason: "EXCHANGE_INVALID" };

  const authority = await input.dal.readAuthority(exchange);
  const refusal = authorityRefusal(authority, exchange.userId, now.getTime());
  if (refusal) return { ok: false, reason: refusal };

  const reusable = await reusableGrant(input, exchange, now);
  if (reusable) return { ok: true, grant: verifiedGrant(reusable) };

  const token = createPreviewAccessSecret();
  const expiresAt = new Date(
    Math.min(
      authority.session!.expiresAtMs,
      now.getTime() + PREVIEW_ACCESS_GRANT_MAX_MS,
    ),
  ).toISOString();
  const grant: VerifiedPreviewAccessGrant = {
    id: crypto.randomUUID(),
    flowId: exchange.flowId,
    kind: exchange.kind,
    sessionId: exchange.sessionId,
    userId: exchange.userId,
    storefrontId: exchange.storefrontId,
    themeId: exchange.themeId,
    previewId: exchange.previewId,
    previewHost: exchange.previewHost,
    expiresAt,
  };
  try {
    await input.dal.insertGrant({
      ...grant,
      tokenHash: await hashPreviewAccessSecret(token),
      now: now.toISOString(),
    });
  } catch {
    return { ok: false, reason: "GRANT_NOT_CREATED" };
  }
  return { ok: true, token, grant };
}

/**
 * The grant a redeem may reuse instead of creating one, read fresh in this
 * redeem's own query; null when none qualifies.
 */
async function reusableGrant(
  input: Readonly<{
    dal: StorefrontPreviewAccessDAL;
    previewHost: string;
    reuse?: Readonly<{ tokens: readonly string[]; minRemainingMs: number }>;
  }>,
  exchange: Readonly<{
    sessionId: string;
    userId: string;
    storefrontId: string;
    themeId: string;
    previewId: string;
    previewHost: string;
    kind: StorefrontPreviewAccessKind;
  }>,
  now: Date,
): Promise<PreviewAccessGrantRecord | null> {
  const tokens = [...new Set(input.reuse?.tokens ?? [])]
    .filter((token) => SECRET_PATTERN.test(token))
    .slice(0, 8);
  if (!input.reuse || tokens.length === 0) return null;
  const nowMs = now.getTime();
  const records = await input.dal.findGrantsByTokenHashes(
    await Promise.all(tokens.map(hashPreviewAccessSecret)),
  );
  const qualifying = records
    .filter(
      (record) =>
        record.sessionId === exchange.sessionId &&
        record.userId === exchange.userId &&
        record.storefrontId === exchange.storefrontId &&
        record.themeId === exchange.themeId &&
        record.previewId === exchange.previewId &&
        record.previewHost === exchange.previewHost &&
        record.kind === exchange.kind &&
        record.activatedAt !== null &&
        Date.parse(record.expiresAt) - nowMs >= input.reuse!.minRemainingMs &&
        grantRefusal(record, input.previewHost, nowMs) === null,
    )
    .sort((a, b) => compareCandidates(a, b));
  return qualifying[0] ?? null;
}

/**
 * Checks one preview request's credential, from the stored grant outwards.
 *
 * A grant that has never been used is activated here, by the first request
 * that passes every other check, and only inside its activation window.
 * Activation is recorded once and extends nothing: the grant's expiry stays
 * what redeem set.
 */
export async function verifyPreviewAccessGrant(input: {
  dal: StorefrontPreviewAccessDAL;
  token: string;
  previewHost: string;
  now?: Date;
  /**
   * Read once for the checks and again for activation, which happens later;
   * a fixed `now` serves both. For tests that let time pass in between.
   */
  clock?: () => Date;
}): Promise<
  | Readonly<{ ok: true; grant: VerifiedPreviewAccessGrant }>
  | Readonly<{ ok: false; reason: PreviewAccessRefusal }>
> {
  if (!SECRET_PATTERN.test(input.token)) {
    return { ok: false, reason: "GRANT_UNKNOWN" };
  }
  const clock = input.clock ?? (() => input.now ?? new Date());
  const record = await input.dal.findGrantByTokenHash(
    await hashPreviewAccessSecret(input.token),
  );
  if (!record) return { ok: false, reason: "GRANT_UNKNOWN" };
  const refusal = grantRefusal(record, input.previewHost, clock().getTime());
  if (refusal) return { ok: false, reason: refusal };
  if (!(await activate(input.dal, record, clock))) {
    return { ok: false, reason: "GRANT_NOT_ACTIVATED" };
  }
  return { ok: true, grant: verifiedGrant(record) };
}

/** Why a stored grant does not authorise a request on this host now, or null. */
function grantRefusal(
  record: PreviewAccessGrantRecord,
  previewHost: string,
  nowMs: number,
): PreviewAccessRefusal | null {
  if (record.revokedAt) return "GRANT_REVOKED";
  if (!(nowMs < Date.parse(record.expiresAt))) return "GRANT_EXPIRED";
  if (record.previewHost !== previewHost) return "HOST_MISMATCH";
  return authorityRefusal(record, record.userId, nowMs);
}

/**
 * Activates a grant on its first verified request, inside its window. An
 * already activated grant needs nothing; past the window, expired or revoked
 * since the read, the statement matches nothing and this says no.
 */
async function activate(
  dal: StorefrontPreviewAccessDAL,
  record: PreviewAccessGrantRecord,
  clock: () => Date,
): Promise<boolean> {
  if (record.activatedAt) return true;
  const activationMs = clock().getTime();
  return dal.activateGrant({
    id: record.id,
    activatableAfter: new Date(
      activationMs - PREVIEW_ACCESS_ACTIVATION_WINDOW_MS,
    ).toISOString(),
    now: new Date(activationMs).toISOString(),
  });
}

function verifiedGrant(
  record: PreviewAccessGrantRecord,
): VerifiedPreviewAccessGrant {
  return {
    id: record.id,
    flowId: record.flowId,
    kind: record.kind,
    sessionId: record.sessionId,
    userId: record.userId,
    storefrontId: record.storefrontId,
    themeId: record.themeId,
    previewId: record.previewId,
    previewHost: record.previewHost,
    expiresAt: record.expiresAt,
  };
}

/**
 * Checks every grant a preview request carries (at most 8, bounded by
 * preview-access-cookies.ts) in one read, and authorises the request with
 * one that holds.
 *
 * Each candidate is a full credential for this host on its own, so any one
 * that passes every check is enough. Which one is decided here, never by the
 * order the browser sent them: activated before not yet activated, then the
 * later expiry, then the later creation, then the id. A grant not yet
 * activated is activated only if it is the one chosen; if its activation
 * fails, the next is tried.
 */
export async function verifyPreviewAccessCandidates(input: {
  dal: StorefrontPreviewAccessDAL;
  tokens: readonly string[];
  previewHost: string;
  now?: Date;
  clock?: () => Date;
}): Promise<
  | Readonly<{ ok: true; grant: VerifiedPreviewAccessGrant }>
  | Readonly<{ ok: false; reason: PreviewAccessRefusal }>
> {
  const clock = input.clock ?? (() => input.now ?? new Date());
  const wellFormed = [...new Set(input.tokens)].filter((token) =>
    SECRET_PATTERN.test(token),
  );
  if (wellFormed.length === 0) return { ok: false, reason: "GRANT_UNKNOWN" };
  const records = await input.dal.findGrantsByTokenHashes(
    await Promise.all(wellFormed.map(hashPreviewAccessSecret)),
  );
  if (records.length === 0) return { ok: false, reason: "GRANT_UNKNOWN" };

  const nowMs = clock().getTime();
  const judged = records.map((record) => ({
    record,
    refusal: grantRefusal(record, input.previewHost, nowMs),
  }));
  const usable = judged
    .filter((entry) => entry.refusal === null)
    .map((entry) => entry.record)
    .sort(compareCandidates);
  for (const record of usable) {
    if (await activate(input.dal, record, clock)) {
      return { ok: true, grant: verifiedGrant(record) };
    }
  }
  if (usable.length > 0) return { ok: false, reason: "GRANT_NOT_ACTIVATED" };
  // Every candidate is refused. Report the newest one's reason: it is the
  // credential the browser most likely meant.
  const newest = [...judged].sort((a, b) =>
    compareCandidates(a.record, b.record, { activatedFirst: false }),
  )[0]!;
  return { ok: false, reason: newest.refusal! };
}

function compareCandidates(
  a: PreviewAccessGrantRecord,
  b: PreviewAccessGrantRecord,
  options: { activatedFirst?: boolean } = {},
): number {
  if (options.activatedFirst !== false) {
    const activated =
      Number(Boolean(b.activatedAt)) - Number(Boolean(a.activatedAt));
    if (activated !== 0) return activated;
  }
  if (a.expiresAt !== b.expiresAt) return a.expiresAt < b.expiresAt ? 1 : -1;
  if (a.createdAt !== b.createdAt) return a.createdAt < b.createdAt ? 1 : -1;
  return a.id < b.id ? 1 : a.id > b.id ? -1 : 0;
}

/** Ends one session's grants; says which previews they were for. */
export function revokePreviewAccessForSession(input: {
  dal: StorefrontPreviewAccessDAL;
  sessionId: string;
  now?: Date;
}) {
  return input.dal.revokeGrants({
    sessionId: input.sessionId,
    now: (input.now ?? new Date()).toISOString(),
  });
}

/** Ends every grant one user holds, in every session. */
export function revokePreviewAccessForUser(input: {
  dal: StorefrontPreviewAccessDAL;
  userId: string;
  now?: Date;
}) {
  return input.dal.revokeGrants({
    userId: input.userId,
    now: (input.now ?? new Date()).toISOString(),
  });
}
